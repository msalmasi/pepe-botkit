#!/usr/bin/env node
// Builds the frame-level dispatch schemas from schemas/index.json:
//   schemas/event.schema.json   event frame + per-type data dispatch
//   schemas/action.schema.json  action frame + per-type data dispatch
//   schemas/result.schema.json  result frame + per-type data dispatch
//   schemas/frame.schema.json   any PCP frame, dispatched on "op"
//
// Usage: node scripts/gen-dispatch.mjs          (write)
//        node scripts/gen-dispatch.mjs --check  (exit 1 if the files on disk are stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "schemas");
const index = JSON.parse(fs.readFileSync(path.join(dir, "index.json"), "utf8"));
const BASE = index.base;
const SCHEMA = "https://json-schema.org/draft/2020-12/schema";
const def = (n) => ({ $ref: `defs.schema.json#/$defs/${n}` });

function typeIs(name) {
  return { properties: { type: { const: name } }, required: ["type"] };
}

/** then-branch: data must match the type's schema; room-bound types also need scope.room. */
function dataThen(schema, requiresRoom) {
  if (!requiresRoom) return { properties: { data: { $ref: schema } } };
  return {
    required: ["scope"],
    properties: { data: { $ref: schema }, scope: { required: ["room"] } },
  };
}

function eventSchema() {
  const branches = Object.entries(index.events).map(([name, e]) => ({
    if: typeIs(name),
    then: dataThen(e.schema, e.requires_room),
  }));
  return {
    $schema: SCHEMA,
    $id: `${BASE}event.schema.json`,
    title: "event frame (connector -> runtime)",
    description: "GENERATED by scripts/gen-dispatch.mjs from index.json - do not edit. Known types validate their data against events/<type>.schema.json; unknown types (newer minor versions, x.<platform>.* extensions) only need a well-formed envelope.",
    allOf: [{ $ref: "envelope.schema.json" }, ...branches],
    type: "object",
    required: ["op", "seq", "type", "connector", "scope", "data"],
    properties: {
      op: { const: "event" },
      seq: def("Seq"),
      type: def("TypeName"),
      connector: { ...def("Id"), description: "Connector instance id (hello.data.connector.id)." },
      scope: def("Scope"),
      data: { type: "object" },
    },
  };
}

function actionSchema() {
  const branches = Object.entries(index.actions).map(([name, a]) => ({
    if: typeIs(name),
    then: dataThen(a.schema, a.requires_room),
  }));
  return {
    $schema: SCHEMA,
    $id: `${BASE}action.schema.json`,
    title: "action frame (runtime -> connector)",
    description: "GENERATED by scripts/gen-dispatch.mjs from index.json - do not edit. The connector answers every action with exactly one final result frame (ref = action id). Unknown action types are answered with error code 'unsupported'.",
    allOf: [{ $ref: "envelope.schema.json" }, ...branches],
    type: "object",
    required: ["op", "type", "data"],
    properties: {
      op: { const: "action" },
      type: def("TypeName"),
      scope: def("Scope"),
      data: { type: "object" },
      timeout_ms: {
        description: "If the connector cannot START the action within this many ms of receiving it, it gives up and returns error 'timeout' (retryable).",
        type: "integer", minimum: 1,
      },
      origin: {
        description: "Who caused this action, for audit logs and platform-side attribution (module, bot instance, triggering event).",
        type: "object",
        properties: {
          bot: def("Id"),
          module: { type: "string", maxLength: 128 },
          event: { ...def("Id"), description: "id of the event frame that triggered this action." },
          user: def("UserRef"),
        },
      },
    },
  };
}

function resultSchema() {
  const resultFor = {};
  for (const [name, a] of Object.entries(index.actions)) resultFor[name] = index.results[a.result];
  const branches = Object.entries(resultFor).map(([name, schema]) => ({
    if: {
      properties: { type: { const: name }, ok: { const: true } },
      required: ["type", "ok"],
      not: { properties: { final: { const: false } }, required: ["final"] },
    },
    then: { properties: { data: { $ref: schema } } },
  }));
  return {
    $schema: SCHEMA,
    $id: `${BASE}result.schema.json`,
    title: "result frame (connector -> runtime)",
    description: "GENERATED by scripts/gen-dispatch.mjs from index.json - do not edit. One final result per action; long-running actions may send interim results with final=false first. Results carry seq and are replayed on resume like events.",
    allOf: [
      { $ref: "envelope.schema.json" },
      {
        if: { properties: { ok: { const: false } }, required: ["ok"] },
        then: { required: ["error"], properties: { error: { $ref: "error.schema.json" } } },
        else: { required: ["data"] },
      },
      ...branches,
    ],
    type: "object",
    required: ["op", "seq", "ref", "type", "ok"],
    properties: {
      op: { const: "result" },
      seq: def("Seq"),
      ref: { ...def("Id"), description: "id of the action frame this answers." },
      type: { ...def("TypeName"), description: "The action type (echoed for logging and validation)." },
      ok: { type: "boolean" },
      final: { type: "boolean", default: true, description: "false = interim progress; another result with the same ref follows." },
      data: { type: "object" },
      error: { type: "object" },
    },
  };
}

function frameSchema() {
  const map = {
    hello: index.control.hello,
    welcome: index.control.welcome,
    event: "event.schema.json",
    action: "action.schema.json",
    result: "result.schema.json",
    ack: index.control.ack,
    ping: index.control.ping,
    pong: index.control.pong,
    flow: index.control.flow,
    bye: index.control.bye,
  };
  return {
    $schema: SCHEMA,
    $id: `${BASE}frame.schema.json`,
    title: "PCP frame",
    description: "GENERATED by scripts/gen-dispatch.mjs from index.json - do not edit. Any single PCP frame, dispatched on 'op'.",
    allOf: [
      { $ref: "envelope.schema.json" },
      ...Object.entries(map).map(([op, ref]) => ({
        if: { properties: { op: { const: op } }, required: ["op"] },
        then: { $ref: ref },
      })),
    ],
  };
}

const outputs = {
  "event.schema.json": eventSchema(),
  "action.schema.json": actionSchema(),
  "result.schema.json": resultSchema(),
  "frame.schema.json": frameSchema(),
};

const check = process.argv.includes("--check");
let stale = [];
for (const [file, json] of Object.entries(outputs)) {
  const p = path.join(dir, file);
  const text = JSON.stringify(json, null, 2) + "\n";
  if (check) {
    const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n") : "";
    if (cur !== text) stale.push(file);
  } else {
    fs.writeFileSync(p, text);
  }
}
if (check && stale.length) {
  console.error(`stale generated schemas: ${stale.join(", ")} - run: node scripts/gen-dispatch.mjs`);
  process.exit(1);
}
if (!check) console.log(`wrote ${Object.keys(outputs).join(", ")}`);
